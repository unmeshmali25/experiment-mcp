"""Seeded generator for the bundled synthetic retail-offer dataset.

The planted probabilities and the spend shift are simulation settings. They
are not estimates from real customers. Running this module rewrites the CSVs
under ``src/experiment_mcp/data/synthetic``.
"""

import argparse
import csv
import json
from pathlib import Path

import numpy as np

from experiment_mcp.dataset import packaged_data_dir
from experiment_mcp.stats.assignment import assign_units

SEED = 20261102
N_CUSTOMERS = 4000
OFFER_ID = "WEEKEND_15"
SALT = "synthetic-v1"
SPLITS = {"control": 0.5, "treatment": 0.5}


def generate(directory: Path, *, seed: int = SEED, n_customers: int = N_CUSTOMERS) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed)
    customer_ids = [f"c{index:05d}" for index in range(n_customers)]
    segments = rng.choice(["new", "active", "lapsed"], size=n_customers, p=[0.3, 0.5, 0.2])
    regions = rng.choice(["NE", "SE", "MW", "W"], size=n_customers)
    pre_period = rng.lognormal(mean=3.2, sigma=0.35, size=n_customers)

    assignment = assign_units(customer_ids, SALT, SPLITS)
    arms = [row.arm for row in assignment.assignments]
    arm_array = np.asarray(arms)
    above_median = pre_period > np.median(pre_period)
    redemption_p = np.where(arm_array == "treatment", 0.12, 0.08).astype(np.float64)
    redemption_p = np.clip(redemption_p + np.where(above_median, 0.01, 0.0), 0, 1)
    redeemed = rng.random(n_customers) < redemption_p
    treatment_shift = np.where(arm_array == "treatment", 2.5, 0.0)
    post_spend = np.clip(0.5 * pre_period + 8.0 + treatment_shift + rng.normal(0, 3, n_customers), 0, None)

    with (directory / "customers.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["customer_id", "segment", "region", "pre_period_spend"])
        for index, customer_id in enumerate(customer_ids):
            writer.writerow(
                [
                    customer_id,
                    segments[index],
                    regions[index],
                    f"{pre_period[index]:.6f}",
                ]
            )
    with (directory / "exposures.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["customer_id", "offer_id", "arm", "redeemed", "post_spend"])
        for index, customer_id in enumerate(customer_ids):
            writer.writerow(
                [
                    customer_id,
                    OFFER_ID,
                    arms[index],
                    int(redeemed[index]),
                    f"{post_spend[index]:.6f}",
                ]
            )
    metadata = {
        "origin": "synthetic",
        "not_real_customers": True,
        "seed": seed,
        "n_customers": n_customers,
        "offer_id": OFFER_ID,
        "salt": SALT,
        "traffic_split": SPLITS,
        "generator": "python -m experiment_mcp.synthetic",
        "planted_dgp": {
            "note": "Simulation settings used by the generator. They are not measured outcomes.",
            "redemption_probability": {
                "control": "0.08, plus 0.01 when pre_period_spend is above the sample median",
                "treatment": "0.12, plus the same 0.01 nudge",
            },
            "post_spend": "max(0, 0.5 * pre_period_spend + 8 + treatment_shift + Normal(0, 3)); treatment_shift is 2.5",
        },
    }
    (directory / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    (directory / "SYNTHETIC.md").write_text(
        "\n".join(
            [
                "# Synthetic retail-offer data",
                "",
                "These files were generated by `python -m experiment_mcp.synthetic`.",
                "They are not real customers, not a sample from a retailer, and not a benchmark result.",
                "The generator plants a redemption gap and a spend shift so the tools have deterministic input.",
                "Do not cite the resulting lift as evidence about a real offer.",
                "",
                "See `metadata.json` for the seed and the planted data-generating process.",
                "",
            ]
        ),
        encoding="utf-8",
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Rewrite the bundled synthetic dataset.")
    parser.add_argument("--out", type=Path, default=packaged_data_dir())
    parser.add_argument("--seed", type=int, default=SEED)
    parser.add_argument("--n", type=int, default=N_CUSTOMERS)
    args = parser.parse_args()
    generate(args.out, seed=args.seed, n_customers=args.n)


if __name__ == "__main__":
    main()
